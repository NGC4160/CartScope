const SHEETS_BY_ID = new Map(ALL_SHEETS.map((sheet) => [sheet.id, sheet]));

export const WIRING_SHEETS: WiringSheet[] = SHEET_ORDER.map((id) => {
  const sheet = SHEETS_BY_ID.get(id);
  if (!sheet) throw new Error(`Missing wiring sheet: ${id}`);
  return sheet;
});

const SHEET_INDEX = new Map(WIRING_SHEETS.map((sheet) => [sheet.id, sheet]));

export function getSheet(id: string): WiringSheet | undefined {
  return SHEET_INDEX.get(id);
}

export function sheetsForPack(packId: string): WiringSheet[] {
  const ids = BY_PACK[packId] ?? [];
  return ids.map((id) => SHEET_INDEX.get(id)).filter((sheet): sheet is WiringSheet => Boolean(sheet));
}

export function packsWithWiring(): string[] {
  return Object.keys(BY_PACK);
}
